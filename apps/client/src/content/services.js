export function getCategory(slug) {
  return serviceCategories.find((c) => c.slug === slug);
}

export function getServicesByCategory(categorySlug) {
  return services.filter((s) => s.category === categorySlug);
}

export function getRelatedServices(service, limit = 2) {
  return getServicesByCategory(service.category)
    .filter((s) => s.slug !== service.slug)
    .slice(0, limit);
}

export function getDepartmentMenu() {
  return serviceCategories.map((category) => {
    const treatments = getServicesByCategory(category.slug);
    return {
      ...category,
      treatments,
      treatmentCount: treatments.length,
    };
  });
}

export function getService(categorySlug, serviceSlug) {
  return services.find((s) => s.category === categorySlug && s.slug === serviceSlug);
}

export function getAllServicePaths() {
  return services.map((s) => ({
    category: s.category,
    slug: s.slug,
  }));
}
